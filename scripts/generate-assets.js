#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync, watch } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = resolve(__dirname, '..');
const publicDir = resolve(rootDir, 'public');
const targetFile = resolve(rootDir, 'src/embedded-assets.ts');

export function generateAssets() {
  try {
    const indexHtml = existsSync(resolve(publicDir, 'index.html'))
      ? readFileSync(resolve(publicDir, 'index.html'), 'utf-8')
      : '<!DOCTYPE html><html><head><title>MCP TTHC</title></head><body><h1>MCP Server Tra Cứu TTHC</h1></body></html>';

    const styleCss = existsSync(resolve(publicDir, 'style.css'))
      ? readFileSync(resolve(publicDir, 'style.css'), 'utf-8')
      : '';

    const appJs = existsSync(resolve(publicDir, 'app.js'))
      ? readFileSync(resolve(publicDir, 'app.js'), 'utf-8')
      : '';

    const logoSvg = existsSync(resolve(publicDir, 'logo.svg'))
      ? readFileSync(resolve(publicDir, 'logo.svg'), 'utf-8')
      : '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"></svg>';

    const content = `// Auto-generated by scripts/generate-assets.js - KHÔNG CHỈNH SỬA THỦ CÔNG
// Tự động nhúng toàn bộ mã HTML/CSS/JS/SVG vào bundle serverless để luôn hiển thị giao diện Web Dashboard hoàn chỉnh
export const EMBEDDED_INDEX_HTML: string = ${JSON.stringify(indexHtml)};
export const EMBEDDED_STYLE_CSS: string = ${JSON.stringify(styleCss)};
export const EMBEDDED_APP_JS: string = ${JSON.stringify(appJs)};
export const EMBEDDED_LOGO_SVG: string = ${JSON.stringify(logoSvg)};
`;

    writeFileSync(targetFile, content, 'utf-8');
    console.log(`[PASS] Đã sinh mã nhúng giao diện vào src/embedded-assets.ts (${(content.length / 1024).toFixed(1)} KB)`);
    return true;
  } catch (err) {
    console.error('[ERROR] Không thể sinh mã nhúng giao diện:', err);
    return false;
  }
}

// Chạy trực tiếp qua CLI
const isDirectCall = process.argv[1] && resolve(process.argv[1]) === __filename;
if (isDirectCall) {
  const isWatchMode = process.argv.includes('--watch') || process.argv.includes('-w');
  const success = generateAssets();
  if (!success && !isWatchMode) {
    process.exit(1);
  }

  if (isWatchMode) {
    console.log(`[WATCH] Đang tự động theo dõi thay đổi trong thư mục: ${publicDir}`);
    let debounceTimer = null;
    watch(publicDir, { recursive: true }, (eventType, filename) => {
      if (!filename || filename.startsWith('.')) return;
      if (debounceTimer) clearTimeout(debounceTimer);
      debounceTimer = setTimeout(() => {
        console.log(`[AUTO-UPDATE] Phát hiện thay đổi tại ${filename}, đang cập nhật mã nhúng...`);
        generateAssets();
      }, 300);
    });
  }
}

